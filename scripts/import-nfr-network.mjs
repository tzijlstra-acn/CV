#!/usr/bin/env node
/**
 * Imports the eight-process NFR network from the public NFRProcesses dataset into
 * portfolio-data/nfr-network.json (brief section 13: the network must be source-derived).
 *
 *   npm run import:nfr-network -- --from ../NFRProcesses   read a local clone
 *   npm run import:nfr-network -- --check                  verify the snapshot is well formed
 *
 * Runs on demand only. The site never fetches the dataset at runtime, and CI uses the committed
 * snapshot. Counts are derived from the source rather than typed by hand.
 */
import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { execFileSync } from 'node:child_process'

const root = path.resolve(import.meta.dirname, '..')
const out = path.join(root, 'portfolio-data', 'nfr-network.json')
const args = process.argv.slice(2)
const fromIdx = args.indexOf('--from')
const EM = String.fromCharCode(0x2014)
const EN = String.fromCharCode(0x2013)

const fail = (m) => {
  console.error(`[import-nfr-network] FAIL: ${m}`)
  process.exit(1)
}

if (args.includes('--check')) {
  const data = JSON.parse(fs.readFileSync(out, 'utf8'))
  if (data.processes?.length !== 8) fail('snapshot must contain eight processes')
  const ids = new Set(data.processes.map((p) => p.id))
  for (const l of data.links) if (!ids.has(l.from) || !ids.has(l.to)) fail(`link ${l.id} does not resolve`)
  console.log(`[import-nfr-network] OK: ${data.processes.length} processes, ${data.links.length} links @ ${data.source.commit.slice(0, 7)}`)
  process.exit(0)
}

if (fromIdx < 0 || !args[fromIdx + 1]) fail('pass --from <path to a local NFRProcesses clone>')
const clone = path.resolve(args[fromIdx + 1])
const file = 'dashboard.html'
const html = fs.readFileSync(path.join(clone, file), 'utf8')
const commit = execFileSync('git', ['-C', clone, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
const dirty = execFileSync('git', ['-C', clone, 'status', '--porcelain', '--', file], { encoding: 'utf8' }).trim()
if (dirty) fail(`${file} has uncommitted changes in the clone; import only committed source`)

/** Extracts a JavaScript array literal that starts at `marker` and evaluates it in an empty context. */
function literal(marker) {
  const start = html.indexOf(marker)
  if (start < 0) fail(`marker not found: ${marker}`)
  const open = html.indexOf('[', start)
  let depth = 0
  let quote = null
  for (let i = open; i < html.length; i++) {
    const c = html[i]
    if (quote) {
      if (c === '\\') i++
      else if (c === quote) quote = null
      continue
    }
    if (c === "'" || c === '"' || c === '`') quote = c
    else if (c === '[') depth++
    else if (c === ']' && --depth === 0) {
      return vm.runInNewContext(`(${html.slice(open, i + 1)})`, Object.create(null), { timeout: 1000 })
    }
  }
  fail(`unterminated literal: ${marker}`)
}

const clean = (s) =>
  String(s)
    .replace(new RegExp(`\\s*${EM}\\s*`, 'g'), ', ')
    .replace(new RegExp(`\\s+${EN}\\s+`, 'g'), ', ')
    .replace(new RegExp(EN, 'g'), '-')
    .trim()

const PROCESSES = literal('var PROCESSES = [')
const EDGES = literal('var edges=[')
const idByAbbr = new Map(PROCESSES.map((p) => [p.abbr.replace(/\s/g, ''), p.id]))
const HUBS = new Set(['RCSA', 'ORM']) // the interconnect view marks these nodes `hub:true`
const hubSource = html.slice(html.indexOf('var nodes={'), html.indexOf('var edges=['))
for (const abbr of HUBS) if (!new RegExp(`${abbr}:\\s*\\{[^}]*hub:true`).test(hubSource)) fail(`hub flag for ${abbr} not found in source`)

const processes = PROCESSES.map((p) => ({
  id: p.id,
  abbreviation: p.abbr,
  name: clean(p.name).replace(/&/g, 'and'),
  hub: HUBS.has(p.abbr.replace(/\s/g, '')),
  steps: p.steps.length,
  decisions: p.steps.filter((s) => s.decision || s.type === 'decision' || s.dec).length,
  lanes: p.lanes.length,
  phases: p.phases.length,
  // Step-level regulatory touchpoints (each step's `rg` list).
  regulations: p.steps.reduce((n, s) => n + (Array.isArray(s.rg) ? s.rg.length : 0), 0),
  aiSteps: p.steps.filter((s) => s.ai).length,
}))

const links = EDGES.map((e) => {
  const from = idByAbbr.get(e.f)
  const to = idByAbbr.get(e.t)
  if (!from || !to) fail(`edge ${e.f} -> ${e.t} does not resolve to a process`)
  return { id: `${from}-to-${to}`, from, to, label: clean(e.l), style: e.dash ? 'dashed' : 'solid' }
})

if (processes.length !== 8) fail(`expected 8 processes, found ${processes.length}`)
const data = {
  $comment: 'Generated by scripts/import-nfr-network.mjs from the public NFRProcesses dataset. Do not edit by hand.',
  source: { repository: 'tzijlstra-acn/NFRProcesses', commit, file, importedAt: new Date().toISOString().slice(0, 10) },
  processes,
  links,
}
fs.writeFileSync(out, JSON.stringify(data, null, 2) + '\n')
console.log(`[import-nfr-network] wrote ${processes.length} processes, ${links.length} links, ${processes.reduce((n, p) => n + p.steps, 0)} steps @ ${commit.slice(0, 7)}`)
