#!/usr/bin/env node
/**
 * Bundle report and budget (brief sections 20.5 and 25): what the first visit downloads, and
 * which chunks load later. Writes qa/bundle/bundle-report.md and .json. Exit 1 over budget.
 */
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'

const root = path.resolve(import.meta.dirname, '..')
const dist = path.join(root, 'dist')
const manifest = JSON.parse(fs.readFileSync(path.join(dist, '.vite/manifest.json'), 'utf8'))
const BUDGET = { initialJsGzip: 175 * 1024, initialCssGzip: 20 * 1024, largestLazyGzip: 60 * 1024 }
// Libraries that must stay out of the first download (explorer, charts, case visuals).
const LAZY_ONLY = [/d3-/, /Evidence\.tsx/, /Capabilities\.tsx/, /Case\.tsx/, /NfrBlueprint/, /S08Economics/, /FabricGraph/]

const gz = (f) => zlib.gzipSync(fs.readFileSync(path.join(dist, f)), { level: 9 }).length
const entryKey = Object.keys(manifest).find((k) => manifest[k].isEntry)
const initial = new Set()
const css = new Set()
const walk = (key) => {
  const chunk = manifest[key]
  if (!chunk || initial.has(chunk.file)) return
  initial.add(chunk.file)
  for (const c of chunk.css ?? []) css.add(c)
  for (const i of chunk.imports ?? []) walk(i)
}
walk(entryKey)
const initialSources = Object.entries(manifest)
  .filter(([, c]) => initial.has(c.file))
  .map(([k]) => k)
const lazy = Object.entries(manifest)
  .filter(([, c]) => c.file.endsWith('.js') && !initial.has(c.file))
  .map(([k, c]) => ({ name: c.name ?? k, file: c.file, gzip: gz(c.file) }))
  .sort((a, b) => b.gzip - a.gzip)

const initialJs = [...initial].reduce((n, f) => n + gz(f), 0)
const initialCss = [...css].reduce((n, f) => n + gz(f), 0)
const leaks = initialSources.filter((s) => LAZY_ONLY.some((re) => re.test(s)))
const kb = (b) => `${(b / 1024).toFixed(1)} KB`
const problems = []
if (initialJs > BUDGET.initialJsGzip) problems.push(`initial JS ${kb(initialJs)} exceeds ${kb(BUDGET.initialJsGzip)}`)
if (initialCss > BUDGET.initialCssGzip) problems.push(`initial CSS ${kb(initialCss)} exceeds ${kb(BUDGET.initialCssGzip)}`)
if (lazy[0] && lazy[0].gzip > BUDGET.largestLazyGzip) problems.push(`largest lazy chunk ${lazy[0].name} ${kb(lazy[0].gzip)} exceeds ${kb(BUDGET.largestLazyGzip)}`)
for (const l of leaks) problems.push(`${l} is in the initial bundle but must be lazy`)

const report = { generatedAt: new Date().toISOString().slice(0, 10), budget: BUDGET, initial: { jsGzip: initialJs, cssGzip: initialCss, files: [...initial, ...css] }, lazy, problems }
fs.mkdirSync(path.join(root, 'qa/bundle'), { recursive: true })
fs.writeFileSync(path.join(root, 'qa/bundle/bundle-report.json'), JSON.stringify(report, null, 2) + '\n')
fs.writeFileSync(
  path.join(root, 'qa/bundle/bundle-report.md'),
  `# Bundle report

Generated by \`node scripts/bundle-report.mjs\` after \`npm run build:portfolio\` (${report.generatedAt}). Sizes are gzip level 9.

| Measure | Size | Budget |
|---|---|---|
| Initial JavaScript (entry and its static imports) | ${kb(initialJs)} | ${kb(BUDGET.initialJsGzip)} |
| Initial CSS | ${kb(initialCss)} | ${kb(BUDGET.initialCssGzip)} |
| Largest lazy chunk | ${lazy[0] ? `${kb(lazy[0].gzip)} (${lazy[0].name})` : 'none'} | ${kb(BUDGET.largestLazyGzip)} |

The first visit loads the shell, the router, Motion, the shell's Radix primitives and the first two scenes. Scenes 3 to 12, the explorer, the capability map, the case pages, the economics charts (d3) and the Work Fabric blueprint load as separate chunks.

## Lazy chunks

| Chunk | Gzip |
|---|---|
${lazy.map((c) => `| ${c.name} | ${kb(c.gzip)} |`).join('\n')}

Result: ${problems.length ? `FAIL\n\n${problems.map((p) => `- ${p}`).join('\n')}` : 'within budget, no lazy-only module in the initial bundle.'}
`,
)
console.log(`[bundle] initial JS ${kb(initialJs)}, CSS ${kb(initialCss)}, ${lazy.length} lazy chunks${problems.length ? `\n  - ${problems.join('\n  - ')}` : ''}`)
if (problems.length) process.exit(1)
