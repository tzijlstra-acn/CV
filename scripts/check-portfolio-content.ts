/**
 * npm run qa:content: content rules on everything visible, and the final copy inventory.
 *
 * - The validated projection (writing rules, confidential terms, claim register).
 * - The prerendered HTML in dist/ (no dashes, no banned phrases outside scripts and styles).
 * - Scene word budgets and title length (at most 12 words, so titles stay on two lines).
 * Writes qa/copy-inventory.md: every public headline string with its word count.
 */
import fs from 'node:fs'
import path from 'node:path'
import { loadPortfolio, ROOT } from '../portfolio-data/build'
import { checkClaims } from '../portfolio-data/claims'
import { checkText, wordCount } from '../portfolio-data/lib/text-rules'

const { result, issues } = loadPortfolio()
if (!result) {
  for (const i of issues) console.error(`  - ${i.where}: ${i.message}`)
  process.exit(1)
}
const site = result.site
const problems = [...issues.map((i) => `${i.where}: ${i.message}`), ...checkClaims(result).map((i) => `${i.where}: ${i.message}`)]

for (const s of site.story) if (wordCount(s.title) > 15) problems.push(`story.${s.id}: title has ${wordCount(s.title)} words`)
for (const c of site.cases) if (wordCount(c.title) > 8) problems.push(`cases.${c.slug}: title has ${wordCount(c.title)} words`)

const dist = path.join(ROOT, 'dist')
if (fs.existsSync(dist)) {
  for (const f of fs.readdirSync(dist, { recursive: true }).map(String).filter((x) => x.endsWith('.html') && x !== 'cv.html')) {
    const visible = fs
      .readFileSync(path.join(dist, f), 'utf8')
      .replace(/<script[\s\S]*?<\/script>/g, ' ')
      .replace(/<style[\s\S]*?<\/style>/g, ' ')
      .replace(/<[^>]+>/g, ' ')
    for (const v of checkText(f, visible)) problems.push(`dist/${f}: ${v.rule}: ${v.excerpt}`)
  }
}

const row = (where: string, text: string) => `| ${where} | ${text.replace(/\|/g, '/')} | ${wordCount(text)} |`
const lines = [
  '# Final copy inventory',
  '',
  `Generated by \`npm run qa:content\` on ${new Date().toISOString().slice(0, 10)}. Every public headline string, with its word count. Canonical copy lives in \`portfolio-data/\`; this file is a read-only view.`,
  '',
  '## Profile',
  '',
  '| Field | Copy | Words |',
  '|---|---|---|',
  row('Title', site.profile.title),
  row('Headline', site.profile.headline),
  row('Supporting', site.profile.supporting),
  row('Proof line', site.profile.proofLine.join(' / ')),
  row('Target roles', site.profile.targetRoles),
  row('Thesis', site.profile.thesis),
  row('Conclusion', site.profile.conclusion),
  '',
  '## Guided story',
  '',
  '| Scene | Title, subhead and caption | Words |',
  '|---|---|---|',
  ...site.story.map((s) => row(`${String(s.number).padStart(2, '0')} ${s.short}`, [s.title, s.subhead, s.caption].filter(Boolean).join(' / '))),
  '',
  '## Role lenses',
  '',
  '| Lens | Opening / conclusion | Words |',
  '|---|---|---|',
  ...site.lenses.map((l) => row(l.label, `${l.opening} / ${l.conclusion}`)),
  '',
  '## Case studies',
  '',
  '| Case | Subtitle / scope boundary | Words |',
  '|---|---|---|',
  ...site.cases.map((c) => row(c.title, `${c.subtitle} / ${c.scopeBoundary}`)),
  '',
]
fs.writeFileSync(path.join(ROOT, 'qa/copy-inventory.md'), lines.join('\n'))

if (problems.length) {
  console.error(`[qa:content] FAIL: ${problems.length} problem(s)`)
  for (const p of problems) console.error(`  - ${p}`)
  process.exit(1)
}
console.log(`[qa:content] OK: copy rules hold on data and prerendered pages; inventory written to qa/copy-inventory.md`)
