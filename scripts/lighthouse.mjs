#!/usr/bin/env node
// Lighthouse CI against the production build served under /CV/ (brief section 25).
// Uses Playwright's Chromium, desktop preset, three runs per URL, filesystem upload only.
// Writes qa/lighthouse/summary.md from the LHCI manifest, with the metrics behind each performance score. On GitHub
// Actions the summary also goes to the job summary, and each URL gets an annotation, so a failure is readable without logs.
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { chromium } from '@playwright/test'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
if (!fs.existsSync(path.join(root, 'dist/index.html'))) {
  console.error('[lighthouse] dist/ missing: run npm run build first')
  process.exit(1)
}
const outDir = path.join(root, 'qa/lighthouse')
fs.rmSync(outDir, { recursive: true, force: true })
fs.rmSync(path.join(root, '.lighthouseci'), { recursive: true, force: true })

const env = { ...process.env, CHROME_PATH: chromium.executablePath() }
// Run the LHCI entry point with Node directly: no shell, so paths with spaces are safe.
const cli = path.join(root, 'node_modules', '@lhci', 'cli', 'src', 'cli.js')
const run = (args) => spawnSync(process.execPath, [cli, ...args], { cwd: root, env, stdio: 'inherit' })

const collect = run(['collect', '--config=lighthouserc.json'])
if (collect.status !== 0) process.exit(collect.status ?? 1)
const upload = run(['upload', '--config=lighthouserc.json'])
if (upload.status !== 0) process.exit(upload.status ?? 1)
const assert = run(['assert', '--config=lighthouserc.json'])

const config = JSON.parse(fs.readFileSync(path.join(root, 'lighthouserc.json'), 'utf8'))
const minPerf = config.ci.assert.assertions['categories:performance'][1].minScore
const manifest = JSON.parse(fs.readFileSync(path.join(outDir, 'manifest.json'), 'utf8'))
const pct = (v) => Math.round(v * 100)
const METRICS = [
  ['first-contentful-paint', 'FCP'],
  ['largest-contentful-paint', 'LCP'],
  ['total-blocking-time', 'TBT'],
  ['cumulative-layout-shift', 'CLS'],
  ['speed-index', 'SI'],
]
const runs = manifest
  .filter((m) => m.isRepresentativeRun)
  .map((m) => {
    const lhr = JSON.parse(fs.readFileSync(m.jsonPath, 'utf8'))
    const metrics = METRICS.map(([id, label]) => `${label} ${lhr.audits[id].displayValue}`).join(', ')
    return { url: m.url.replace('http://localhost', '').replace(/^:\d+/, ''), s: m.summary, metrics, report: path.basename(m.htmlPath) }
  })
const rows = runs.map((r) => `| \`${r.url}\` | ${pct(r.s.performance)} | ${pct(r.s.accessibility)} | ${pct(r.s['best-practices'])} | ${pct(r.s.seo)} | ${r.metrics} | \`${r.report}\` |`)
const summary = `# Lighthouse summary\n\nGenerated by \`npm run qa:lighthouse\`: Lighthouse CI ${'0.15.1'}, desktop preset, ${3} runs per URL, median representative run shown. Budgets: performance 90, accessibility 95, best practices 95, SEO 90 (warning).\n\n| URL | Performance | Accessibility | Best practices | SEO | Metrics | Report |\n|---|---|---|---|---|---|---|\n${rows.join('\n')}\n\nAssertion result: ${assert.status === 0 ? 'pass' : 'FAIL (see console output)'}.\n`
fs.writeFileSync(path.join(outDir, 'summary.md'), summary)

if (process.env.GITHUB_ACTIONS) {
  if (process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, summary)
  for (const r of runs) {
    const level = r.s.performance < minPerf ? 'error' : 'notice'
    console.log(`::${level} title=Lighthouse ${r.url}::Performance ${pct(r.s.performance)}, accessibility ${pct(r.s.accessibility)}, best practices ${pct(r.s['best-practices'])}, SEO ${pct(r.s.seo)}. ${r.metrics}`)
  }
}

fs.rmSync(path.join(root, '.lighthouseci'), { recursive: true, force: true })
console.log(`[lighthouse] ${assert.status === 0 ? 'OK' : 'FAIL'}: summary in qa/lighthouse/summary.md`)
process.exit(assert.status ?? 1)
